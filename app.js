  function renderDescription(root, item, data, field) {
    const value = descriptionText(item, data, field);
    if (!editing && !value.trim()) return;

    const section = document.createElement('section');
    section.className = 'edit-slot';
    if (editing) {
      const label = document.createElement('label');
      label.htmlFor = `description-${field.key}`;
      label.textContent = field.label;
      const textarea = document.createElement('textarea');
      textarea.id = label.htmlFor;
      textarea.className = 'edit-text';
      textarea.value = value;
      section.append(label, textarea);

      const initial = field.initial(item.id);
      let reset;
      if (initial !== undefined) {
        reset = document.createElement('button');
        reset.type = 'button';
        reset.className = 'secondary small-button';
        reset.textContent = '初期文に戻す';
        reset.setAttribute('aria-label', `${field.label}を初期文に戻す`);
        reset.disabled = !Object.hasOwn(data, field.key);
        reset.onclick = () => {
          delete data[field.key];
          textarea.value = initial;
          reset.disabled = true;
        };
        section.append(reset);
      }
      textarea.oninput = () => {
        data[field.key] = textarea.value;
        if (reset) reset.disabled = false;
      };
    } else {
      const heading = document.createElement('h3');
      heading.textContent = field.label;
      const paragraph = document.createElement('p');
      paragraph.className = 'detail-text';
      paragraph.textContent = value;
      section.append(heading, paragraph);
    }
    root.append(section);
  }

